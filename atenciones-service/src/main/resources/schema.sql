CREATE TABLE IF NOT EXISTS atencion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    cita_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    area VARCHAR(60) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_atencion TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL,
    CONSTRAINT uq_atencion_codigo UNIQUE (codigo),
    CONSTRAINT uq_atencion_cita UNIQUE (cita_id)
);

CREATE INDEX IF NOT EXISTS idx_atencion_paciente ON atencion (paciente_id);
CREATE INDEX IF NOT EXISTS idx_atencion_estado ON atencion (estado);
