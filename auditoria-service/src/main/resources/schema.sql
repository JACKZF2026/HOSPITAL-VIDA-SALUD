CREATE TABLE IF NOT EXISTS evento_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id VARCHAR(60) NOT NULL,
    tipo_evento VARCHAR(60) NOT NULL,
    origen VARCHAR(60) NOT NULL,
    recurso_id VARCHAR(60),
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30),
    payload CLOB,
    fecha_evento VARCHAR(60),
    fecha_registro TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_tipo ON evento_auditoria (tipo_evento);
CREATE INDEX IF NOT EXISTS idx_auditoria_recurso ON evento_auditoria (recurso_id);
