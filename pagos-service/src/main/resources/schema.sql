CREATE TABLE IF NOT EXISTS pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_operacion VARCHAR(40) NOT NULL,
    paciente_id BIGINT NOT NULL,
    concepto VARCHAR(150) NOT NULL,
    monto DECIMAL(12, 2) NOT NULL,
    medio_pago VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_pago TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP NOT NULL,
    CONSTRAINT uq_pago_operacion UNIQUE (numero_operacion)
);

CREATE INDEX IF NOT EXISTS idx_pago_paciente ON pago (paciente_id);
CREATE INDEX IF NOT EXISTS idx_pago_estado ON pago (estado);
